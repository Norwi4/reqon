use crate::{
    generated_headers::{self, HeaderRow, Override},
    model::*,
    theme::Theme,
    widgets::{self as w, Icon, rect},
};
use eframe::egui::{self, Ui, pos2, vec2};
use std::collections::BTreeMap;

fn cell_label(ui: &mut Ui, bounds: egui::Rect, label: egui::Label) -> egui::Response {
    let mut cell = ui.new_child(
        egui::UiBuilder::new()
            .max_rect(bounds)
            .layout(egui::Layout::left_to_right(egui::Align::Center)),
    );
    cell.set_clip_rect(bounds.intersect(ui.clip_rect()));
    cell.add(label)
}

pub fn draw(ui: &mut Ui, request: &mut Request, vars: &BTreeMap<String, String>, t: Theme) -> bool {
    let mut rows = generated_headers::rows(request, vars);
    let id = ui
        .scope_id()
        .with(("generated-headers-visible", &request.id));
    let mut visible = ui
        .ctx()
        .data_mut(|d| d.get_temp::<bool>(id))
        .unwrap_or(false);
    ui.horizontal(|ui| {
        ui.label(egui::RichText::new("Headers").size(12.).color(t.muted));
        let label = if visible {
            "Hide auto-generated headers".into()
        } else {
            format!("{} hidden", rows.len())
        };
        if ui
            .add(
                egui::Button::new(egui::RichText::new(label).size(12.).color(t.muted)).frame(false),
            )
            .on_hover_text("Show or hide automatically generated headers")
            .clicked()
        {
            visible = !visible;
        }
    });
    ui.ctx().data_mut(|d| d.insert_temp(id, visible));
    ui.add_space(6.);
    let before = rows.clone();
    let changed = w::pairs_with_generated(
        ui,
        &mut request.headers,
        ["Name", "Value"],
        t,
        true,
        if visible { &mut rows } else { &mut [] },
    );
    for (row, previous) in rows.iter().zip(before) {
        if row.setting != previous.setting {
            generated_headers::set_override(request, &row.name, row.setting.clone());
        }
    }
    changed
}

pub fn table_rows(
    ui: &mut Ui,
    rows: &mut [HeaderRow],
    width: f32,
    first: f32,
    second: f32,
    t: Theme,
) -> bool {
    let mut changed = false;
    for row in rows {
        let r = ui.allocate_space(vec2(width, 35.5)).1;
        ui.painter().rect_filled(r, 0, t.surface);
        ui.push_id(("auto-header", row.name.clone()), |ui| {
            let editable = row.editable();
            let tip = if row.name == "Content-Length" {
                "Calculated from the actual request body. Managed by the HTTP transport."
            } else if row.name == "Host" {
                "Generated from the URL. Edit or uncheck to omit Host. HTTP/2 still requires :authority."
            } else if !editable {
                "Generated by authorization. Configure this header in the Auth tab."
            } else {
                "Automatically generated. Edit the value or uncheck to omit this header."
            };
            let mut enabled = !row.setting.disabled;
            ui.add_enabled_ui(editable, |ui| {
                if w::table_checkbox(
                    ui,
                    rect(r.left() + 3., r.top(), 24., r.height()),
                    &mut enabled,
                    &format!("Include {}. {tip}", row.name),
                    t,
                ) {
                    row.setting.disabled = !enabled;
                    changed = true;
                }
            });
            let name_rect = rect(r.left() + 36., r.top() + 1., first - 46., r.height() - 2.);
            cell_label(ui,
                name_rect,
                egui::Label::new(egui::RichText::new(&row.name).size(13.).color(t.muted))
                    .halign(egui::Align::Min)
                    .truncate(),
            )
            .on_hover_text(format!("{}\n{tip}", row.name));
            let mut value = row
                .setting
                .value
                .clone()
                .unwrap_or_else(|| row.automatic.clone());
            let value_rect = rect(
                r.left() + first + 10.,
                r.top() + 1.,
                second - first - 20.,
                r.height() - 2.,
            );
            if editable {
                if ui
                    .put(
                        value_rect,
                        w::table_text(ui, "value", &mut value, r.height() - 2.)
                            .text_color(if enabled { t.text } else { t.muted }),
                    )
                    .on_hover_text(format!("Automatic value: {}", row.automatic))
                    .changed()
                {
                    row.setting.value = Some(value);
                    changed = true;
                }
            } else {
                cell_label(ui,
                    value_rect,
                    egui::Label::new(egui::RichText::new(value).size(13.).color(t.muted))
                        .halign(egui::Align::Min)
                        .truncate(),
                )
                .on_hover_text(tip);
            }
            let status = if row.setting.disabled {
                "Disabled"
            } else if row.setting.value.is_some() {
                "Overridden"
            } else {
                "Auto-generated"
            };
            cell_label(ui,
                rect(
                    r.left() + second + 10.,
                    r.top() + 1.,
                    (width - second - 68.).max(30.),
                    r.height() - 2.,
                ),
                egui::Label::new(egui::RichText::new(status).size(12.).color(t.muted)).halign(egui::Align::Min).truncate(),
            )
            .on_hover_text(tip);
            if row.setting != Override::default()
                && w::icon_button(
                    ui,
                    rect(r.right() - 42., r.center().y - 13., 26., 26.),
                    Icon::Undo,
                    &format!("Reset {} to automatic value", row.name),
                    t,
                )
                .clicked()
            {
                row.setting = Override::default();
                changed = true;
            }
        });
        w::line(ui, pos2(r.left(), r.bottom()), r.right_bottom(), t.border);
    }
    changed
}
