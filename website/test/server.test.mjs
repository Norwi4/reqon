import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, mkdir, rm } from 'node:fs/promises';
import { once } from 'node:events';
import path from 'node:path';
import os from 'node:os';
import { createWebsite, parseRange } from '../server.mjs';
import { LocalReleases, ReleaseCatalog } from '../src/releases.mjs';

test('byte ranges support continuation, suffixes and reject invalid requests', () => {
  assert.deepEqual(parseRange('bytes=2-4', 10), { start: 2, end: 4 });
  assert.deepEqual(parseRange('bytes=3-', 10), { start: 3, end: 9 });
  assert.deepEqual(parseRange('bytes=-3', 10), { start: 7, end: 9 });
  assert.deepEqual(parseRange('bytes=0-100', 10), { start: 0, end: 9 });
  for (const input of ['bytes=20-', 'bytes=4-2', 'bytes=-0', 'bytes=0-1,4-5', 'garbage']) assert.equal(parseRange(input, 10), false);
});

test('real download, HEAD, range resume, checksums, safe paths, redirect and 404', async t => {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'reqon-server-'));
  const publicDir = path.join(dir, 'public'); const releaseDir = path.join(dir, 'releases');
  await mkdir(publicDir); await mkdir(releaseDir);
  await writeFile(path.join(publicDir, 'index.html'), '<h1>Reqon</h1>');
  await writeFile(path.join(publicDir, '404.html'), '<h1>404</h1>');
  const filename = 'Reqon-Setup-0.13.8-win64.exe';
  await writeFile(path.join(releaseDir, filename), '0123456789');
  await writeFile(path.join(dir, 'secret.txt'), 'secret');
  const local = new LocalReleases(releaseDir, publicDir);
  const catalog = new ReleaseCatalog(local);
  const server = createWebsite({ publicDir, releaseDir, catalog });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await rm(dir, { recursive: true, force: true }); });
  const origin = `http://127.0.0.1:${server.address().port}`;
  const response = await fetch(`${origin}/api/releases`);
  assert.equal(response.status, 200); const data = await response.json(); assert.equal(data.latest.windows.version, '0.13.8');
  const url = `${origin}${data.latest.windows.url}`;
  const head = await fetch(url, { method: 'HEAD' }); assert.equal(head.headers.get('content-length'), '10'); assert.equal(await head.text(), '');
  const full = await fetch(url); assert.equal(await full.text(), '0123456789'); assert.match(full.headers.get('content-disposition'), /^attachment/);
  const range = await fetch(url, { headers: { Range: 'bytes=2-5' } }); assert.equal(range.status, 206); assert.equal(range.headers.get('content-range'), 'bytes 2-5/10'); assert.equal(await range.text(), '2345');
  const invalid = await fetch(url, { headers: { Range: 'bytes=50-' } }); assert.equal(invalid.status, 416);
  const changed = await fetch(url, { headers: { Range: 'bytes=2-', 'If-Range': '"outdated"' } }); assert.equal(changed.status, 200);
  const checksum = await fetch(`${url}.sha256`); assert.match(await checksum.text(), /^[a-f0-9]{64}  Reqon/);
  const redirect = await fetch(`${origin}/download/latest/windows`, { redirect: 'manual' }); assert.equal(redirect.status, 302); assert.equal(redirect.headers.get('location'), `/files/${filename}`);
  for (const route of ['/files/secret.txt', '/not-a-page', '/api/secret', '/%252e%252e/secret.txt', '/%2e%2e%5csecret.txt', '/.env']) assert.notEqual((await fetch(origin + route)).status, 200);
  assert.equal((await fetch(origin + '/missing', { method: 'HEAD' })).status, 404);
  assert.equal((await fetch(origin + '/', { method: 'POST' })).status, 405);
  assert.equal((await fetch(origin + '/healthz')).status, 200);
  catalog.github = { repository: 'Norwi4/reqon', load: async () => ({ releases: [{ ...data.latest.windows, id: 'github:1', source: 'github', url: 'https://github.com/Norwi4/reqon/releases/download/v0.13.8/app.exe' }], stale: false }) };
  const remote = await fetch(`${origin}/download/latest/windows`, { redirect: 'manual' });
  assert.equal(remote.headers.get('location'), 'https://github.com/Norwi4/reqon/releases/download/v0.13.8/app.exe');
  assert.equal((await fetch(url)).status, 200);
});
